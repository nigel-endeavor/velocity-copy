CREATE OR REPLACE VIEW pbi_i90_ethernet_service AS
SELECT s.service_id,
       s.tenant_id AS 'Tenant ID',
       s.current_inventory AS 'Current Inventory',
       es.product_type AS 'Product Type',
       es.port_speed AS 'Port Speed',
       es.ea_speed AS 'EA Speed',
       es.mtu AS 'MTU',
       es.mux AS 'MUX',
       es.vlan_for_eline AS 'VLAN for E-Line',
       es.vlan_tagging AS 'VLAN Tagging',
       es.vlan_id AS 'VLAN ID',
       es.cable_category AS 'Cable Category',
       es.cable_shielding AS 'Cable Shielding',
       es.data_center_name AS 'Data Center Name',
       es.provider_circuit_id AS 'Provider Circuit ID',
       es.access_type AS 'Access Type',
       es.interface_connector AS 'Interface Connector',
       es.access_hours AS 'Access Hours',
       es.manned AS 'Manned',
       es.loa_required AS 'LOA Required',
       es.handoff_fiber_mode AS 'Handoff Fiber Mode',
       es.handoff_connector_type AS 'Handoff Connector Type',
       es.clli_code AS 'CLLI Code',
       es.pop_clli AS 'POP CLLI',
       es.alternate_pop_clli AS 'Alternate POP CLLI',
       es.floor AS 'Floor',
       es.npa_nxx AS 'NPA NXX',
       es.cfa AS 'CFA',
       es.z_address_1 AS 'Z Address',
			 es.z_address_2 AS 'Z Address 2',
			 es.z_city AS 'Z City',
			 es.z_state_province AS 'Z State',
			 es.z_postal_code AS 'Z Zip',
			 es.z_country AS 'Z Country',
       es.z_data_center_name AS 'Z Data Center Name',
       es.z_provider_circuit_id AS 'Z Provider Circuit ID',
       es.z_building_status AS 'Z Building Status',
       es.z_access_type AS 'Z Access Type',
       es.z_interface_connector AS 'Z Interface Connector',
       es.z_access_hours AS 'Z Access Hours',
       es.z_manned AS 'Z Manned',
       es.z_loa_required AS 'Z LOA Required',
       es.z_inside_wiring_required AS 'Z Inside Wiring Required',
       es.z_handoff_media_type AS 'Z Handoff Media Type',
       es.z_handoff_fiber_mode AS 'Z Handoff Fiber Mode',
       es.z_handoff_connector_type AS 'Z Handoff Connector Type',
       es.z_clli_code AS 'Z CLLI Code',
       es.z_pop_clli AS 'Z POP CLLI',
       es.z_alternate_pop_clli AS 'Z Alternate POP CLLI',
       es.z_floor AS 'Z Floor',
       es.z_npa_nxx AS 'Z NPA NXX',
       es.z_dmarc AS 'Z DMARC',
       es.z_cfa AS 'Z CFA',
       access_speed AS 'Access Speed'
FROM service s
     JOIN ethernet_service es ON s.service_id = es.service_id
WHERE s.tenant_id != (SELECT tenant_id FROM v_tenant WHERE name = 'Endeavor')
