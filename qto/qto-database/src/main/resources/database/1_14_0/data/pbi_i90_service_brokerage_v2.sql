CREATE OR REPLACE VIEW pbi_i90_service_brokerage AS
SELECT s.service_id AS 'Service ID',
       s.tenant_id AS 'Tenant ID',
       s.current_inventory AS 'Current Inventory',
       submitted_in_adv_to_provider AS 'Submitted in Adv to Provider',
       parent_tsd AS 'Parent TSD',
       submitted_in_adv_to_tsd AS 'Submitted in Adv to TSD',
       cie_teamed_deal_info AS 'CIE Teamed Deal Info',
       sfa_opportunity_num  AS 'SFA Opportunity Num',
       net_provider_points  AS 'Net Provider Points',
       promotions AS 'Promotions',
       commissionable_mrc AS 'Commissionable MRC',
       commissionable_nrc AS 'Commissionable NRC',
       commissionable_arc AS 'Commissionable ARC',
       commissions_supplier AS 'Commissions Supplier',
       commissions_account_number AS 'Commissions Account Number',
       sub_agent_percent / 100 AS 'Sub Agent Percent',
       sub_agent AS 'Sub Agent',
       sub_agent_rep AS 'Sub Agent Rep',
       secondary_agency AS 'Secondary Agency',
       secondary_agency_rep AS 'Secondary Agency Rep',
       tertiary_agency AS 'Tertiary Agency',
       tertiary_agency_rep AS 'Tertiary Agency Rep',
       referral AS 'Referral',
       referral_name AS 'Referral Name',
       company_referral_percent / 100 AS 'Company Referral Percent',
       spiff_amount AS 'Spiff Amount',
       customer_order_alias AS 'Customer Order Alias',
       engineer_resource AS 'Engineer Resource',
       engineer_resource_allocation / 100 AS 'Engineer Resource Allocation',
       commission_payment_type AS 'Commission Payment Type',
       expected_commission AS 'Expected Commission',
       commission_reduction_percent / 100 AS 'Commission Reduction Percent',
       commission_icb AS 'Commission ICB',
       internal_commissions_comments AS 'Internal Commissions Comments',
       gross_profit_mrc_multiplier AS 'Gross Profit MRC Multiplier',
       percent_resides_from_carrier / 100 AS 'Percent Resides From Carrier',
       gross_profit_mrc AS 'Gross Profit MRC',
       gross_profit AS 'Gross Profit',
       gross_profit_mrc_needs_to_be_edited AS 'Gross Profit MRC Needs to be Edited',
       gross_profit_needs_to_be_edited AS 'Gross Profit Needs to be Edited',
       gross_profit_mrc_override AS 'Gross Profit MRC Override',
       gross_profit_override  AS 'Gross Profit Override',
       rep_gross_profit_production AS 'Rep Gross Profit Production',
       total_contract_value AS 'Total Contract Value',
       uplift_mrc AS 'Uplift MRC',
       subaccount_mrc AS 'Subaccount MRC',
       rep_gross_profit_needs_to_be_edited AS 'Rep Gross Profit Needs to be Edited'
FROM service_brokerage sb
     JOIN service s ON sb.service_id = s.service_id
WHERE s.tenant_id != (SELECT tenant_id FROM v_tenant WHERE name = 'Endeavor');
